export function courseLD(en) {
  const row = COURSE[en];
  return row || [en, en];
}

export function noteLD(en) {
  return NOTE[en] || [en, en];
}

export function formLD(bg) {
  return FORM[bg] || { fr: bg, de: bg };
}

export function teacherLD(en, lang) {
  const table = lang === "fr"
    ? [
        ["Chief Asst. Prof. Dr ", "Dr (maître-assistant) "],
        ["Assoc. Prof. Dr ", "Dr (maître de conférences) "],
        ["Prof. DSc ", "Prof. D. Sc. "],
        ["Prof. Dr ", "Prof. "],
        ["Researcher ", "Chercheur "],
      ]
    : [
        ["Chief Asst. Prof. Dr ", "Hauptass. Dr. "],
        ["Assoc. Prof. Dr ", "Doz. Dr. "],
        ["Prof. DSc ", "Prof. D. Sc. "],
        ["Prof. Dr ", "Prof. Dr. "],
        ["Researcher ", "Forscher "],
      ];
  for (const [from, to] of table) {
    if (en.startsWith(from)) return to + en.slice(from.length);
  }
  return en;
}

export function roomLD(en, lang) {
  const table = lang === "fr" ? ROOM_FR : ROOM_DE;
  let out = en;
  for (const [from, to] of table) out = out.replaceAll(from, to);
  return out;
}

